// Studio interaction smoke test. Run the dev server with VITE_MOCK_STUDIO=1 so edits never touch a real draft.
import puppeteer from 'puppeteer-core';
const BASE = process.env.WEB ?? 'http://127.0.0.1:3010';
const CHROME = process.env.CHROME ?? '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';
const [email, pw] = JSON.parse(process.env.SMOKE_ADMIN ?? '[]');
const results = []; const check = (n, ok, x = '') => results.push([ok ? 'PASS' : 'FAIL', n, x]);
const navTo = async (page, label) => { await page.evaluate((l) => { [...document.querySelectorAll('.studio-nav button')].find((b) => b.textContent.trim().startsWith(l)).click(); }, label); await new Promise((r) => setTimeout(r, 500)); };
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const browser = await puppeteer.launch({ executablePath: CHROME, headless: true, args: ['--no-sandbox'] });
const page = await browser.newPage();
await page.setViewport({ width: 1440, height: 900 });
const errors = []; page.on('pageerror', (e) => errors.push(String(e)));
await page.goto(`${BASE}/login`, { waitUntil: 'networkidle2' });
await page.type('#em', email); await page.type('#pw', pw);
await Promise.all([page.waitForSelector('.topbar'), page.click('button.primary')]);
await page.goto(`${BASE}/studio/agents`, { waitUntil: 'networkidle2' });
await page.waitForSelector('.studio-content details.entry');
check('studio: agents section renders entries', (await page.$$('.studio-content details.entry')).length >= 10);
// disable compliance_screen -> invariant error
await page.evaluate(() => { const d = document.querySelector('details[data-path="agents.compliance_screen"]'); d.open = true; });
await page.click('details[data-path="agents.compliance_screen"] button[role="switch"]');
await sleep(1800);
const bar = await page.$eval('.studio-bar', (e) => e.textContent);
check('studio: invariant violation surfaces in bar', /error/i.test(bar), bar.trim().slice(0, 60));
check('studio: draft autosaved', /Draft saved/.test(bar), bar.trim().slice(0, 60));
const side = await page.$eval('.studio-side', (e) => e.textContent);
check('studio: error lists invariant id', /INV_COMPLIANCE_ENABLED/.test(side));
await page.screenshot({ path: `${process.env.SHOTS ?? '.'}/shot-studio-error.png` });
await page.click('.studio-bar .btn.primary');
await page.waitForSelector('.dialog');
await sleep(600);
const dis = await page.$eval('.dialog-foot .btn.primary', (b) => b.disabled);
check('studio: publish blocked while invariant violated', dis);
await page.keyboard.press('Escape');
await sleep(200);
check('studio: Esc closes dialog', !(await page.$('.dialog')));
// fix it and publish
await page.click('details[data-path="agents.compliance_screen"] button[role="switch"]');
await sleep(1500);
await page.click('.studio-bar .btn.primary'); await page.waitForSelector('.dialog');
await page.type('#pn', 'smoke publish'); await sleep(600);
await page.click('.dialog-foot .btn.primary'); await sleep(800);
await navTo(page, 'Versions');
const rows = await page.$$eval('.table tbody tr', (r) => r.length);
check('studio: version published (2 rows)', rows === 2, `${rows}`);
// providers panel: key entry cleared after save, never shown
await navTo(page, 'Providers');
await page.waitForSelector('input[type=password]');
await page.type('input[type=password]', 'sk-test-secret-value');
await page.click('form .btn.primary'); await sleep(600);
const val = await page.$eval('input[type=password]', (i) => i.value);
const html = await page.content();
check('providers: key input cleared after save', val === '');
check('providers: secret never present in DOM', !html.includes('sk-test-secret-value'));
check('providers: has_key badge shown', /key set/.test(html));
await page.click('.card .btn.sm:not(.primary):not(.danger)'); await sleep(800);
check('providers: test connection lists models', /models discovered/.test(await page.content()));
await navTo(page, 'LLM');
check('model picker has datalist after discovery', (await page.$$('datalist option')).length > 0);
check('no uncaught page errors', errors.length === 0, errors.join('|'));
await browser.close();
for (const r of results) console.log(r.join('  '));
process.exit(results.some((r) => r[0] === 'FAIL') ? 1 : 0);
