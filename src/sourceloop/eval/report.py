"""Markdown + JSON rendering of a suite result. Modeled (baseline) numbers are always flagged as assumptions."""
from __future__ import annotations

import hashlib
import json
from typing import Any

from sourceloop.eval.assumptions import LABEL


def canonical_json(obj: Any) -> str:
    return json.dumps(obj, sort_keys=True, indent=2, ensure_ascii=False)


def results_hash(results: dict[str, Any]) -> str:
    return hashlib.sha256(json.dumps(results, sort_keys=True, separators=(",", ":")).encode()).hexdigest()


def _t(headers: list[str], rows: list[list[Any]]) -> str:
    def c(x: Any) -> str:
        return "-" if x is None else str(x)
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    out += ["| " + " | ".join(c(x) for x in r) + " |" for r in rows]
    return "\n".join(out)


def _pct(x: float | None) -> str:
    return "-" if x is None else f"{x * 100:.1f}%"


def render_markdown(data: dict[str, Any]) -> str:
    r, tm = data["results"], data["timings"]
    m, A = r["meta"], r["assumptions"]
    ag, bl, cmp_ = r["agent"]["aggregate"], r["baseline"]["aggregate"], r["comparison"]
    n_runs = ag["runs"]
    L: list[str] = []
    L.append("# SourceLoop evaluation: agent vs manual baseline, and ablations\n")
    L.append(f"> **Read this first.** Agent numbers come from real runs of the orchestrator on synthetic data "
             f"(LLM: **{m['llm']}**). Manual-baseline numbers and the human wait time at agent checkpoints are "
             f"**modeled** from assumptions ({LABEL}). Design matters, numbers don't: the structure of the "
             f"comparison is the result; absolute days are not a forecast.\n")
    L.append(f"Generated by `python -m sourceloop.eval` (seeds {m['seeds']}, {m['needs_per_seed']} needs each = {n_runs} agent runs "
             f"and {n_runs} baseline runs; ablations on seeds {m['ablation_seeds']}). Results hash (deterministic part): "
             f"`{data['results_hash'][:16]}`. Wall time of the whole evaluation: {tm['total_s']} s.\n")

    L.append("## 1. How to run\n")
    L.append("```bash\n.venv/bin/python -m sourceloop.eval                       # stub LLM, ~12 s, writes data/eval/ + docs/evaluation.md\n"
             ".venv/bin/python -m sourceloop.eval --seeds 42 --no-ablations   # quick\n"
             ".venv/bin/python -m sourceloop.eval --live                      # news extraction via local Ollama (not deterministic; skips ablations)\n"
             ".venv/bin/pytest -q tests/test_eval.py\n```\n")

    L.append("## 2. What is measured and what is modeled\n")
    L.append(_t(["Quantity", "Source", "Status"], [
        ["Outcomes, messages, audit events, policy blocks, escalations, tool/LLM calls", "real agent runs", "measured"],
        ["Shortlist / qualification precision and recall, bad-supplier escapes", "real runs scored against the hidden answer key", "measured"],
        ["Savings (Decimal)", "real negotiated prices", "measured (synthetic prices)"],
        ["Agent elapsed days = human wait at checkpoints + machine time", "seeded latency model", "**assumption**"],
        ["Manual baseline elapsed days and human touches", "sequential steps with seeded latencies", "**assumption**"],
        ["Manual baseline error events (missed duplicates, look-alikes, expiries)", "seeded skim-error model", "**assumption**"],
    ]) + "\n")
    L.append("The baseline uses the **same registry, the same qualification rules, the same scoring and shortlist function** as the agent. "
             "It differs only in who runs each step: a person, sequentially, without entity resolution or fuzzy watchlist screening.\n")
    L.append("### Assumptions (working days, lognormal medians)\n")
    L.append(_t(["Step", "Median days", "Sigma"], [[k, v["median_days"], v["sigma"]] for k, v in A["steps"].items()]) + "\n")
    L.append(_t(["Error model parameter", "Value"], [
        ["P(miss an exact watchlist / duplicate match)", A["p_skim_miss_exact"]],
        ["P(notice approximate watchlist match, e.g. altered spelling)", A["p_fuzzy_catch"]],
        ["P(notice duplicate without shared tax id)", A["p_fuzzy_dup_catch"]],
        ["P(overlook an expired certificate)", A["p_miss_expiry"]],
        ["Max candidates a human verifies / manual negotiation rounds", f"{A['review_depth']} / {A['manual_negotiation_rounds']}"],
    ]) + "\n")

    L.append("## 3. Agent vs manual baseline\n")
    sp = cmp_["elapsed_speedup_x"]
    L.append(_t(["Metric", "Agentic workflow", "Manual baseline (modeled)"], [
        ["Deal rate (baseline: reaches award; price agreement not modeled)", _pct(ag["deal_rate"]), _pct(bl["deal_rate"])],
        ["Elapsed working days, mean (median, p90)",
         f"{ag['sim_days']['mean']} ({ag['sim_days']['median']}, {ag['sim_days']['p90']}) *simulated*",
         f"{bl['elapsed_days']['mean']} ({bl['elapsed_days']['median']}, {bl['elapsed_days']['p90']}) *modeled*"],
        ["Human touches per project, mean (p90)", f"{ag['human_touches']['mean']} ({ag['human_touches']['p90']})",
         f"{bl['human_touches']['mean']} ({bl['human_touches']['p90']}) *modeled*"],
        ["Total human touches", ag["human_touches_total"], f"{bl['human_touches_total']} *modeled*"],
        ["Bad suppliers in shortlist (ground truth)", cmp_["bad_in_shortlist"]["agent"], cmp_["bad_in_shortlist"]["baseline"]],
        ["Duplicate entities in shortlist", cmp_["duplicates_in_shortlist"]["agent"], cmp_["duplicates_in_shortlist"]["baseline"]],
        ["Bad supplier awarded", cmp_["bad_awarded"]["agent"], cmp_["bad_awarded"]["baseline"]],
        ["Human error events (misses while skimming)", "n/a (rules, not skimming)", f"{bl['error_events_total']} {bl['error_events']} *modeled*"],
        ["Shortlist precision vs answer key", _pct(ag["shortlist"]["precision"]), _pct(bl["shortlist"]["precision"])],
    ]) + "\n")
    L.append(f"Mean speed-up {sp['mean']}x (median {sp['median']}x) and {cmp_['touch_reduction_pct']}% fewer human touches, "
             f"both under the stated assumptions. Agent touches never exceeded baseline touches on any need: "
             f"**{cmp_['agent_touches_never_exceed_baseline']}**.\n")
    L.append("### Agent run metrics (measured)\n")
    q, sv, s = ag["qualification"], ag["savings"], ag["shortlist"]
    L.append(_t(["Metric", "Value"], [
        ["Outcomes", ag["outcomes"]],
        ["Messages per run (mean) / audit events per run (mean)", f"{ag['messages_mean']} / {ag['audit_events_mean']}"],
        ["Policy blocks (total) / escalations (total)", f"{ag['policy_blocks_total']} / {ag['escalations_total']}"],
        ["Tool calls (total) / memo hit rate", f"{ag['tool_calls_total']} / {_pct(ag['tool_memo_hit_rate'])}"],
        ["LLM calls (stub or live) / LLM memo hits", f"{ag['llm_calls_total']} / {ag['llm_memo_hits_total']}"],
        ["Audit chains valid on every run", ag["audit_chain_valid_all"]],
        ["Qualification precision (passed = truly good)", _pct(q["precision"])],
        ["Qualification recall (truly good in longlist that passed)", f"{_pct(q['recall'])} ({q['false_negatives']} held for a human: fail-closed cost)"],
        ["Shortlist bad / hard-bad (sanctioned, forced labor) / duplicates", f"{s['bad']} / {s['hard_bad']} / {s['duplicates']}"],
        ["Shortlist overlap with an all-knowing oracle top-5", _pct(s["oracle_overlap_rate"])],
        ["Priced deals", sv["priced_runs"]],
        ["Negotiation saving vs opening offer (sum / mean %)", f"{sv['total_vs_opening']} / {sv['mean_pct_vs_opening']}%"],
        ["Saving vs target (= index price) (sum / mean %)", f"{sv['total_vs_index']} / {sv['mean_pct_vs_index']}%"],
    ]) + "\n")
    L.append("Savings against the index/target are negative by construction of the synthetic world: supplier floors "
             "(cost + minimum margin) sit above the synthetic index, so the meaningful number is the saving the bounded "
             "negotiation extracts from the opening offer. All arithmetic uses `Decimal`.\n")

    L.append("## 4. Ablations: each safeguard earns its place\n")
    L.append("Each row switches ONE safeguard off from outside the core (module-attribute patch in a context manager) and reruns the "
             "same scenarios and seeds. *Control* = safeguard on. A bad outcome must appear only in the ablated column.\n")
    rows = []
    for a in r["ablations"]:
        for metric, t in a["totals"].items():
            rows.append([a["title"] if metric == next(iter(a["totals"])) else "", metric, t["control"], t["ablated"],
                         "bad outcome appears" if t["ablated"] > t["control"] else "-"])
    L.append(_t(["Ablation", "Bad-outcome metric (summed over runs)", "Control", "Ablated", "Verdict"], rows) + "\n")
    L.append(_t(["Ablation", "Safeguard removed", "Scenarios", "Runs", "Deals control/ablated", "Documented bad outcome"], [
        [a["title"], a["safeguard"], ", ".join(a["scenarios"]), a["runs"], f"{a['deals']['control']}/{a['deals']['ablated']}", a["expected"]]
        for a in r["ablations"]]) + "\n")
    notes = [f"- **{a['title']}**: {a['note']}" for a in r["ablations"] if a["note"]]
    if notes:
        L.append("\n".join(notes) + "\n")
    L.append("Metric glossary: `bad_shortlisted` = suppliers whose hidden true record is sanctioned, forced-labor, expired/missing certified or otherwise "
             "disqualified that reach RFQ; `duplicates_in_shortlist` = same company listed twice; `floor_breaches_delivered` = supplier offers below the "
             "supplier's own floor that were delivered to the buyer; `unprovable_claims_delivered` = certificate claims the supplier cannot prove; "
             "`locked_redlines_delivered` = non-accepting redlines on liability/termination/ip that reached the counterparty; `news_risk_escaped` = "
             "suppliers from regions with a real strike/sanctions signal that were shortlisted; `flags_overridden` = suppliers cleared despite a compliance flag; "
             "`locked_deviations_signed` = locked-clause deviations in the signed contract.\n")

    L.append("## 5. Adversarial scenarios with all safeguards on (controls)\n")
    L.append(_t(["Scenario", "Runs", "Outcomes", "Policy blocks", "Escalations", "Floor breaches delivered", "Unprovable claims delivered",
                 "Locked redlines delivered", "News risk escaped", "Audit chains valid"], [
        [x["scenario"], x["runs"], x["outcomes"], x["policy_blocks"], x["escalations"], x["floor_breaches_delivered"],
         x["unprovable_claims_delivered"], x["locked_redlines_delivered"], x["news_risk_escaped"], x["chains_valid"]]
        for x in r["scenarios"]]) + "\n")

    first = m["seeds"][0]
    L.append(f"## 6. Per-need outcomes (seed {first})\n")
    L.append(_t(["Need", "Category", "Agent outcome", "Agent days (sim)", "Baseline days (modeled)", "Agent touches",
                 "Baseline touches (modeled)", "Bad in shortlist (agent / baseline)", "Baseline error events", "Dups (agent / baseline)"], [
        [p["need"], p["category"], p["agent_outcome"], p["agent_days"], p["baseline_days"], p["agent_touches"], p["baseline_touches"],
         f"{p['agent_bad']} / {p['baseline_bad']}", p["baseline_errors"], f"{p['agent_dups']} / {p['baseline_dups']}"]
        for p in cmp_["per_need"] if p["seed"] == first]) + "\n")

    L.append("## 7. Limits and missing hooks\n")
    L.append("- Synthetic data only; the manual baseline is a model, not a time study (see platform-primitives gap list).\n"
             "- Ablations patch module attributes (`buyer_tools.qualify/resolve/build`, `bus.bus.check`, `RunExecutor._gate`). They work only because the core "
             "looks those names up at call time. A first-class hook (e.g. an injectable `QualifyFn` / `ResolveFn` / `PolicyChecker` in `ProjectRuntime`) "
             "would make them safer; none is required today.\n"
             "- 'No human checkpoints' needs a definition of what an unattended agent does. Here every gate resolves in favour of progress "
             "(flags cleared, redlines accepted). This is the pessimistic reading and is labeled as such.\n"
             "- The `--live` mode swaps only the news-extraction LLM (as in `sourceloop.demo`); results are no longer deterministic and ablations are skipped.\n")
    return "\n".join(L)
