/** AI-interaction disclosure (EU AI Act Art. 50 style). The server derives `ai_generated` from the sender kind; the fallback
 *  below only covers older payloads/mocks: every bus sender except the deterministic orchestrator is an AI agent. */
export const ORCHESTRATOR_SENDER = 'orchestrator';

export function isAiGenerated(from: string, flag?: boolean): boolean {
  if (typeof flag === 'boolean') return flag;
  return from !== '' && from !== ORCHESTRATOR_SENDER;
}

