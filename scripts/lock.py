#!/usr/bin/env python3
"""Generate / verify the pinned Python lock files from the *installed* environment.

requirements.lock      closure of [project].dependencies          (runtime; used by the Dockerfile and CI)
requirements-dev.lock  runtime + closure of the [dev] extra       (CI, local dev)

These two files are the source of truth for reproducible installs (uv is not used in this repo).
Regenerate after changing pyproject.toml dependencies:
    python3 -m venv /tmp/lockenv && /tmp/lockenv/bin/pip install -e '.[dev]' && /tmp/lockenv/bin/python scripts/lock.py
Verify (CI): install from the lock files, then `python scripts/lock.py --check` (fails if pyproject and locks disagree).
"""
from __future__ import annotations

import importlib.metadata as md
import sys
from pathlib import Path

from packaging.requirements import Requirement
from packaging.utils import canonicalize_name as canon

ROOT = Path(__file__).resolve().parent.parent
HEADER = "# {title}\n# Source of truth for reproducible installs; generated by scripts/lock.py. Do not hand-edit.\n"


def _closure(dists: dict, roots: list[str]) -> set[str]:
    seen: set[str] = set()
    stack = list(roots)
    while stack:
        n = canon(stack.pop())
        if n in seen or n not in dists:
            continue
        seen.add(n)
        for r in dists[n].requires or []:
            q = Requirement(r)
            if q.marker is None or q.marker.evaluate({"extra": ""}):
                stack.append(q.name)
    return seen


def render() -> dict[str, str]:
    dists = {canon(d.metadata["Name"]): d for d in md.distributions()}
    runtime, dev = [], []
    for r in dists["sourceloop"].requires or []:
        q = Requirement(r)
        (dev if q.marker and "extra" in str(q.marker) else runtime).append(q.name)
    out = {}
    for fname, names, title in (
        ("requirements.lock", _closure(dists, runtime), "Runtime lock (closure of [project].dependencies)"),
        ("requirements-dev.lock", _closure(dists, runtime + dev), "Dev lock (runtime + [dev] extra closure)"),
    ):
        lines = [HEADER.format(title=title)]
        lines += [f"{dists[n].metadata['Name']}=={dists[n].version}\n" for n in sorted(names) if n != "sourceloop"]
        out[fname] = "".join(lines)
    return out


def main() -> int:
    rendered = render()
    if "--check" in sys.argv:
        bad = [f for f, txt in rendered.items() if (ROOT / f).read_text() != txt]
        if bad:
            print("lock files out of date or environment differs from locks:", ", ".join(bad), file=sys.stderr)
            return 1
        print("lock files match the installed environment")
        return 0
    for f, txt in rendered.items():
        (ROOT / f).write_text(txt)
        print("wrote", f)
    return 0


if __name__ == "__main__":
    sys.exit(main())
